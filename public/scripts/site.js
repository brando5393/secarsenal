// Plain JS in public/, referenced with <script is:inline src="/scripts/site.js">
// in BaseLayout.astro so Astro serves it verbatim as a real external
// file instead of running it through its bundler (which, for scripts
// this small, inlines the compiled output directly into every page's
// HTML — and our CSP is `script-src 'self'` with no 'unsafe-inline',
// so an inlined <script> is simply blocked from running at all).
// Each feature below no-ops on pages that don't have its markup.

// --- Shared Pagefind loader -------------------------------------------
// Pagefind's index is generated by the postbuild step (see
// package.json), so `/pagefind/pagefind.js` only exists after `npm run
// build` — it 404s under `astro dev`. Every search feature below treats
// a failed import as "no full-text index available" and falls back to
// a simpler in-page match rather than breaking.
let pagefindPromise;
function loadPagefind() {
  if (!pagefindPromise) {
    pagefindPromise = import('/pagefind/pagefind.js').catch(() => null);
  }
  return pagefindPromise;
}

// Escapes text for safe insertion into innerHTML. Pagefind's search
// results come from this site's own indexed content, but that content
// ultimately originates from external sources synced from 8 upstream
// projects (Kali, BlackArch, GitHub READMEs, etc.) — Astro escapes it
// once at build time, but Pagefind's excerpt generation works from the
// page's rendered *text* (post-unescaping), so a tool/OS name
// containing HTML-special characters would otherwise reach innerHTML
// here unescaped a second time. Always escape untrusted text before
// building HTML strings by hand instead of using real DOM APIs.
function escapeHtml(str) {
  return str.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

// Same as escapeHtml, but re-allows Pagefind's own <mark>/</mark> match
// highlighting (the only markup Pagefind itself ever adds to an
// excerpt) after escaping everything else.
function escapeExcerpt(str) {
  return escapeHtml(str).replace(/&lt;(\/?)mark&gt;/g, '<$1mark>');
}

function initHomeSearch() {
  const input = document.getElementById('site-search');
  const results = document.getElementById('search-results');
  if (!input || !results) return;

  const CARD_CLASS =
    'card block rounded-lg border border-gray-800 bg-gray-900 p-5 no-underline transition-colors hover:border-emerald-500';

  input.addEventListener('focus', () => loadPagefind());

  input.addEventListener('input', async () => {
    const query = input.value.trim();
    results.innerHTML = '';
    if (!query) return;
    const pagefind = await loadPagefind();
    if (!pagefind) {
      results.innerHTML =
        '<p class="text-sm text-gray-500 col-span-full">Search index only available in a production build (npm run build).</p>';
      return;
    }
    const search = await pagefind.search(query);
    const items = await Promise.all(search.results.slice(0, 10).map((r) => r.data()));
    results.innerHTML = items
      .map((item) => {
        const type = item.filters?.type?.[0];
        const badge = type
          ? `<span class="mb-1 inline-block rounded-full bg-gray-800 px-2 py-0.5 text-[10px] uppercase tracking-wide text-gray-400">${escapeHtml(type)}</span>`
          : '';
        const title = escapeHtml(item.meta?.title ?? item.url);
        const href = escapeHtml(item.url);
        return `<a class="${CARD_CLASS}" href="${href}">${badge}<h3 class="mb-1 font-semibold text-white">${title}</h3><p class="text-sm text-gray-400">${escapeExcerpt(item.excerpt)}</p></a>`;
      })
      .join('');
  });
}

// Normalizes a URL (absolute or Pagefind's site-relative form) down to
// a bare pathname with no trailing slash, so a card's `href` and a
// Pagefind result's `url` compare equal regardless of how each was
// written.
function urlPath(url) {
  return new URL(url, location.origin).pathname.replace(/\/$/, '');
}

// Shared by the OS and Tools index pages: a text query first tries
// Pagefind (full-text, scoped to `type`) and falls back to a plain
// substring match on each card's `data-name` when Pagefind's index
// isn't available (`astro dev`) or hasn't loaded yet. Returns `null`
// (meaning "no active query, everything passes") for an empty query.
async function matchingSlugs(query, cards, pagefindType) {
  if (!query) return null;
  const pagefind = await loadPagefind();
  if (!pagefind) {
    const q = query.toLowerCase();
    return new Set(cards.filter((c) => (c.dataset.name ?? '').includes(q)).map((c) => urlPath(c.href)));
  }
  const search = await pagefind.search(query, { filters: { type: [pagefindType] } });
  const datas = await Promise.all(search.results.map((r) => r.data()));
  return new Set(datas.map((d) => urlPath(d.url)));
}

function initOsIndex() {
  const filterBar = document.getElementById('filter-bar');
  const teamFilterBar = document.getElementById('team-filter-bar');
  const searchInput = document.getElementById('os-name-filter');
  const resultCount = document.getElementById('os-result-count');
  if (!filterBar) return;

  const buttons = [...filterBar.querySelectorAll('button')];
  const teamButtons = teamFilterBar ? [...teamFilterBar.querySelectorAll('button')] : [];
  const cards = [...document.querySelectorAll('#card-grid .card')];

  let activeCategory = 'all';
  let activeTeam = 'all';
  let activeSlugs = null;
  let queryToken = 0;

  function applyFilters() {
    let visible = 0;
    for (const card of cards) {
      const matchesQuery = activeSlugs === null || activeSlugs.has(urlPath(card.href));
      const matchesCategory = activeCategory === 'all' || card.dataset.category === activeCategory;
      const matchesTeam = activeTeam === 'all' || card.dataset.team === activeTeam;
      const show = matchesQuery && matchesCategory && matchesTeam;
      card.style.display = show ? '' : 'none';
      if (show) visible++;
    }
    if (resultCount) resultCount.textContent = `Showing ${visible} of ${cards.length} operating systems`;
  }

  buttons.forEach((btn) => {
    btn.addEventListener('click', () => {
      buttons.forEach((b) => b.setAttribute('aria-pressed', 'false'));
      btn.setAttribute('aria-pressed', 'true');
      activeCategory = btn.dataset.category;
      applyFilters();
    });
  });

  teamButtons.forEach((btn) => {
    btn.addEventListener('click', () => {
      teamButtons.forEach((b) => b.setAttribute('aria-pressed', 'false'));
      btn.setAttribute('aria-pressed', 'true');
      activeTeam = btn.dataset.team;
      applyFilters();
    });
  });

  if (searchInput) {
    searchInput.addEventListener('input', async () => {
      const token = ++queryToken;
      const slugs = await matchingSlugs(searchInput.value.trim(), cards, 'Operating System');
      if (token !== queryToken) return; // a newer keystroke superseded this query
      activeSlugs = slugs;
      applyFilters();
    });
  }

  applyFilters();
}

function initToolsFilter() {
  const nameFilter = document.getElementById('name-filter');
  const categoryFilter = document.getElementById('category-filter');
  const teamFilterBar = document.getElementById('team-filter-bar');
  const resultCount = document.getElementById('result-count');
  if (!nameFilter || !categoryFilter || !resultCount) return;

  const cards = [...document.querySelectorAll('#card-grid .card')];
  const teamButtons = teamFilterBar ? [...teamFilterBar.querySelectorAll('button')] : [];

  // Pre-select a category when arriving from the homepage's "top
  // categories" widget (/tools?category=webapp) or any other link.
  const requestedCategory = new URLSearchParams(location.search).get('category');
  if (requestedCategory && [...categoryFilter.options].some((o) => o.value === requestedCategory)) {
    categoryFilter.value = requestedCategory;
  }

  let activeSlugs = null;
  let activeTeam = 'all';
  let queryToken = 0;

  function applyFilters() {
    const category = categoryFilter.value;
    let visible = 0;
    for (const card of cards) {
      const matchesQuery = activeSlugs === null || activeSlugs.has(urlPath(card.href));
      const cardCategories = (card.dataset.categories ?? '').split(',');
      const matchesCategory = category === 'all' || cardCategories.includes(category);
      const matchesTeam = activeTeam === 'all' || card.dataset.team === activeTeam;
      const show = matchesQuery && matchesCategory && matchesTeam;
      card.style.display = show ? '' : 'none';
      if (show) visible++;
    }
    resultCount.textContent = `Showing ${visible} of ${cards.length} tools`;
  }

  nameFilter.addEventListener('input', async () => {
    const token = ++queryToken;
    const slugs = await matchingSlugs(nameFilter.value.trim(), cards, 'Tool');
    if (token !== queryToken) return; // a newer keystroke superseded this query
    activeSlugs = slugs;
    applyFilters();
  });
  categoryFilter.addEventListener('change', applyFilters);
  teamButtons.forEach((btn) => {
    btn.addEventListener('click', () => {
      teamButtons.forEach((b) => b.setAttribute('aria-pressed', 'false'));
      btn.setAttribute('aria-pressed', 'true');
      activeTeam = btn.dataset.team;
      applyFilters();
    });
  });
  applyFilters();
}

// --- "Top categories" personalization -------------------------------
// Static-site-friendly personalization: we track which tool categories
// a visitor looks at in their own browser's localStorage (never sent
// anywhere — there's no backend to send it to), then reorder the
// homepage's pre-rendered top-categories pool to surface whichever of
// those categories the visitor has actually shown interest in. New
// visitors with no history simply see the global default ranking that
// was computed at build time.
const CATEGORY_VISITS_KEY = 'sa_category_visits';

function trackCategoryVisit() {
  const meta = document.getElementById('page-meta');
  const categories = meta?.dataset.categories?.split(',').filter(Boolean);
  if (!categories || categories.length === 0) return;

  try {
    const raw = localStorage.getItem(CATEGORY_VISITS_KEY);
    const counts = raw ? JSON.parse(raw) : {};
    for (const c of categories) counts[c] = (counts[c] ?? 0) + 1;
    localStorage.setItem(CATEGORY_VISITS_KEY, JSON.stringify(counts));
  } catch {
    // localStorage unavailable (private browsing, disabled, etc.) —
    // personalization just won't happen for this visitor, no big deal.
  }
}

function initTopCategories() {
  const widget = document.getElementById('top-categories-widget');
  if (!widget) return;

  const items = [...widget.querySelectorAll('[data-category]')];

  let visits = {};
  try {
    visits = JSON.parse(localStorage.getItem(CATEGORY_VISITS_KEY) ?? '{}');
  } catch {
    visits = {};
  }

  const hasHistory = Object.keys(visits).length > 0;
  if (!hasHistory) return; // keep the server-rendered global default as-is

  // Re-rank the pre-rendered pool (not just the visible top 5) by
  // personal visit count, falling back to the original global order
  // (its index in `items`) as a tiebreaker so categories the visitor
  // hasn't seen yet still fill out the list sensibly.
  const ranked = items
    .map((el, originalIndex) => ({ el, originalIndex, visits: visits[el.dataset.category] ?? 0 }))
    .sort((a, b) => b.visits - a.visits || a.originalIndex - b.originalIndex);

  ranked.forEach(({ el }, i) => {
    widget.appendChild(el); // re-append in ranked order
    el.classList.toggle('hidden', i >= 5);
  });

  const subtitle = document.getElementById('top-categories-subtitle');
  if (subtitle) subtitle.textContent = 'Based on the categories you’ve been browsing.';
}

// --- First-visit acknowledgment ---------------------------------------
const ACK_KEY = 'sa_disclaimer_ack_v1';

function initAckModal() {
  const modal = document.getElementById('ack-modal');
  const button = document.getElementById('ack-modal-accept');
  if (!modal || !button) return;

  let acknowledged = false;
  try {
    acknowledged = localStorage.getItem(ACK_KEY) === '1';
  } catch {
    acknowledged = false; // if storage is unavailable, don't block usage on it
  }
  if (acknowledged) return;

  // `flex` is applied here (not baked into the static class list) so it's
  // never present at the same time as the `hidden` attribute — Tailwind's
  // `.flex{display:flex}` is an author-origin rule and beats the browser's
  // default `[hidden]{display:none}` in the cascade regardless of
  // specificity, so having both at once leaves the full-viewport backdrop
  // visually shown (and swallowing every click on the page under it) even
  // while `.hidden` reads `true` in the DOM.
  const previouslyFocused = document.activeElement;
  const focusable = [...modal.querySelectorAll('button, a[href]')];

  // A `role="alertdialog"` is only modal to a screen reader if keyboard
  // focus is actually confined to it — without this, a keyboard user
  // tabs straight through the visually-blocked page underneath.
  function trapFocus(e) {
    if (e.key !== 'Tab' || focusable.length === 0) return;
    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (e.shiftKey && document.activeElement === first) {
      e.preventDefault();
      last.focus();
    } else if (!e.shiftKey && document.activeElement === last) {
      e.preventDefault();
      first.focus();
    }
  }

  modal.hidden = false;
  modal.classList.add('flex');
  modal.addEventListener('keydown', trapFocus);
  button.focus();

  button.addEventListener('click', () => {
    modal.hidden = true;
    modal.classList.remove('flex');
    modal.removeEventListener('keydown', trapFocus);
    if (previouslyFocused instanceof HTMLElement) previouslyFocused.focus();
    try {
      localStorage.setItem(ACK_KEY, '1');
    } catch {
      // Nothing we can do if storage is blocked — just let them through
      // for this session rather than trap them behind the modal.
    }
  });
}

